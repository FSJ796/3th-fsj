"""提示词模板：统一采用“角色 + 任务 + 输出格式”的三段式写法（T2/T3/T4）。"""

# 招聘 JD：角色设定为资深 HR，输出要求结构化
JD_SYSTEM = '你是一名资深 HR，擅长撰写招聘文案。'


def build_jd_prompt(title):
    """为指定岗位构造生成 JD 的提示词（任务 + 输出格式）。"""
    return (
        f'请为「{title}」岗位撰写一份招聘 JD，'
        f'要求包含三部分：岗位职责、任职要求、薪资范围。'
        f'使用简洁中文，全文约 150 字。'
    )


# 制度问答：限定只根据资料回答，资料没有的内容必须回答“不知道”，防止模型胡编
QA_SYSTEM = '你是一名企业制度助手，只能根据提供的资料回答，资料中没有的内容请回答“不知道”。'


def build_qa_prompt(context, question):
    """把检索到的资料作为上下文注入提示词，再附上用户问题。"""
    return f'【资料】\n{context}\n\n【问题】\n{question}\n\n请用简洁中文回答。'


# 数据点评：要求客观、简短，避免模型输出长篇分析
COMMENT_SYSTEM = '你是一名企业 HR 数据分析师，点评客观、简洁、有建设性。'


def build_salary_comment_prompt(data_text):
    """把考勤/薪资结构化数据转成的文本注入提示词，要求一句简短点评。"""
    return f'{data_text}\n请结合考勤与薪资数据生成一句简短、客观的点评或改进建议（约 40 字）。'
